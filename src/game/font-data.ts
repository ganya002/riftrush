function g(...lines: string[]): string[] {
  if (lines.length !== 7) throw new Error(`glyph height ${lines.length}`);
  for (const line of lines) {
    if (line.length !== 5) throw new Error(`glyph width ${line.length} [${line}]`);
  }
  return lines;
}

