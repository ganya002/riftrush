function rowsOf(pattern: string, label: string): readonly string[] {
  const rows = pattern.split('|');
  if (rows.length !== 7 || rows.some((row) => row.length !== 5 || /[^.#]/.test(row))) {
    throw new Error(`Glyph "${label}" must be 7 rows of 5 made from . and #`);
  }
  return rows;
}

export const GLYPHS: Readonly<Record<string, readonly string[]>> = Object.freeze(
  Object.fromEntries(Object.entries(RAW).map(([char, pattern]) => [char, rowsOf(pattern, char)])),
);

/** Atlas order. Space and punctuation are included so gaps stay monospace. */
export const FONT_CHARS = Object.keys(GLYPHS).join('');

const KNOWN = new Set(FONT_CHARS);

/** ASCII-uppercase text limited to glyphs the bitmap font can draw. */
export function fitText(message: string): string {
  let out = '';
  for (let index = 0; index < message.length; index += 1) {
    const char = message[index];
    if (char === '\n') {
      out += '\n';
      continue;
    }
    if (char === '\r') continue;
    const upper = char >= 'a' && char <= 'z' ? String.fromCharCode(char.charCodeAt(0) - 32) : char;
    out += KNOWN.has(upper) ? upper : '?';
  }
  return out;
}

/** Monospace advance: each cell is 6 source pixels times the BitmapText scale. */
export function textWidth(message: string, scale: number): number {
  const fitted = fitText(message);
  let width = 0;
  let line = 0;
  const step = 6 * scale;
  for (const char of fitted) {
    if (char === '\n') {
      width = Math.max(width, line);
      line = 0;
      continue;
    }
    line += step;
  }
  return Math.max(width, line);
}

export function textHeight(scale: number): number {
  return 8 * scale;
}
